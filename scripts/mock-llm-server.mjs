#!/usr/bin/env node
/**
 * Tiny OpenAI-compatible stub server used for local development and tests.
 *
 * It lets you exercise the full LLM code path — provider resolution, request
 * construction, JSON parsing, model labelling, token accounting — with no API
 * key, no cost and no network. It is NOT a real model: it returns canned
 * structured payloads that match each agent's schema.
 *
 *   node scripts/mock-llm-server.mjs            # listens on 0.0.0.0:4010
 *   PORT=4011 node scripts/mock-llm-server.mjs
 *
 * Then point ApplyPilot at it:
 *   AI_PROVIDER=custom OPENAI_BASE_URL=http://127.0.0.1:4010/v1 OPENAI_API_KEY=mock
 */
import { createServer } from "node:http";

const PORT = Number(process.env.PORT ?? 4010);

function jsonFor(system, user) {
  const s = `${system}\n${user}`.toLowerCase();

  if (s.includes("cover letter") || s.includes("lettre de motivation")) {
    return {
      title: "Cover letter — generated by the local stub model",
      content:
        "<p>Dear hiring team,</p><p>This letter was produced by the <strong>stub model</strong> to prove the LLM code path is wired correctly: provider resolution, JSON schema handling and persistence all ran end to end.</p><p>Replace this server with a real provider (Ollama, OpenRouter, Groq, Gemini) to get genuine generated prose.</p><p>Kind regards,<br/>Candidate</p>",
    };
  }

  if (s.includes("follow-up") || s.includes("follow up") || s.includes("relance")) {
    return {
      subject: "Following up on my application (stub model)",
      body: "Hello,\n\nI wanted to follow up on the application I sent last week and check whether you need any additional information from me.\n\nThis message was generated by the local stub model.\n\nBest regards,\nCandidate",
    };
  }

  if (s.includes("compatibility") || s.includes("match") || s.includes("scoring")) {
    return {
      explanation:
        "Explanation produced by the stub model: the numeric score and every dimension are still computed by ApplyPilot's deterministic matching engine, never invented by the language model.",
    };
  }

  if (s.includes("research") || s.includes("company") || s.includes("entreprise")) {
    return {
      description: "Company summary produced by the stub model — verify against the source page before use.",
      industry: null,
      size: null,
      headquarters: null,
      technologies: [],
      hiringSignals: [],
      confidence: 0.2,
      notes: "Generated by scripts/mock-llm-server.mjs (no external network).",
    };
  }

  // default: email drafting
  return {
    subject: "Application — generated by the local stub model",
    body: "Hello,\n\nThis draft came from the stub LLM server, which proves the provider layer, structured output parsing and approval flow all work without a paid API key.\n\nBest regards,\nCandidate",
    highlights: ["Stub-model draft — swap in a real provider for production prose"],
  };
}

const server = createServer((req, res) => {
  if (req.method === "GET" && req.url === "/api/tags") {
    // Ollama-style probe
    res.writeHead(200, { "content-type": "application/json" });
    res.end(JSON.stringify({ models: [{ name: "llama3.2" }] }));
    return;
  }

  if (req.method !== "POST" || !req.url?.includes("chat/completions")) {
    res.writeHead(404, { "content-type": "application/json" });
    res.end(JSON.stringify({ error: "Not found" }));
    return;
  }

  let raw = "";
  req.on("data", (chunk) => {
    raw += chunk;
  });
  req.on("end", () => {
    let payload = { messages: [], model: "stub" };
    try {
      payload = JSON.parse(raw || "{}");
    } catch {
      /* ignore */
    }

    const system = payload.messages?.find((m) => m.role === "system")?.content ?? "";
    const user = payload.messages?.find((m) => m.role === "user")?.content ?? "";
    const content = JSON.stringify(jsonFor(system, user));

    res.writeHead(200, { "content-type": "application/json" });
    res.end(
      JSON.stringify({
        id: "chatcmpl-stub",
        object: "chat.completion",
        created: Math.floor(Date.now() / 1000),
        model: payload.model ?? "stub-model",
        choices: [{ index: 0, message: { role: "assistant", content }, finish_reason: "stop" }],
        usage: {
          prompt_tokens: Math.ceil((system.length + user.length) / 4),
          completion_tokens: Math.ceil(content.length / 4),
          total_tokens: Math.ceil((system.length + user.length + content.length) / 4),
        },
      }),
    );
  });
});

server.listen(PORT, "127.0.0.1", () => {
  console.log(`[mock-llm] OpenAI-compatible stub listening on http://127.0.0.1:${PORT}/v1`);
});
