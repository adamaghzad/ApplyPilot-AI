const DEMO_STATUSES: ApplicationStatus[] = [
  "DRAFT_READY",
  "AWAITING_APPROVAL",
  "AWAITING_APPROVAL",
  "SCHEDULED",
  "SENT",
  "SENT",
  "REPLIED",
  "INTERVIEW",
];

export type DemoSummary = {
  companies: number;
  jobs: number;
  applications: number;
  contacts: number;
  seeded: boolean;
};

/** Seeds the demonstration dataset for a user. Idempotent per company name. */
export async function seedDemoData(userId: string): Promise<DemoSummary> {
  const db = getDb();
  const [profile] = await db.select().from(candidateProfiles).where(eq(candidateProfiles.userId, userId)).limit(1);

  await db.update(users).set({ demoMode: true, updatedAt: new Date() }).where(eq(users.id, userId));

  const run = await startAgentRun({ userId, agent: "DISCOVERY", input: { demo: true }, message: "Loading demonstration dataset" });

  let companiesCreated = 0;
  let jobsCreated = 0;
  let contactsCreated = 0;

  const createdJobs: (typeof jobListings.$inferSelect)[] = [];
  const jobToCompany = new Map<string, (typeof companies.$inferSelect)>();

  for (const demoCompany of DEMO_COMPANIES) {
    const [company] = await db
      .insert(companies)
      .values({
        userId,
        name: demoCompany.name,
        website: demoCompany.website,
        industry: demoCompany.industry,
        size: demoCompany.size,
        headquarters: demoCompany.headquarters,
        targetTitle: demoCompany.targetTitle,
        description: demoCompany.description,
        technologies: demoCompany.technologies,
        careersUrl: `${demoCompany.website}/careers`,
        researchStatus: "READY",
        researchConfidence: 0.68,
        researchNotes: "Demonstration research snapshot — re-run the Research Agent to fetch live public sources.",
        researchData: {
          sources: [
            { url: demoCompany.website, kind: "WEBSITE", title: demoCompany.name, snippet: demoCompany.description, fetchedAt: new Date().toISOString() },
            { url: `${demoCompany.website}/careers`, kind: "CAREERS", title: `${demoCompany.name} careers`, snippet: "Public careers page", fetchedAt: new Date().toISOString() },
          ],
          applicationProcess: "Apply through the public careers page or by email to the recruitment address.",
          techStack: demoCompany.technologies,
          hiringSignals: ["Careers page actively invites applications", "Uses an applicant tracking system with public job feeds"],
        },
        lastResearchedAt: new Date(),
      })
      .onConflictDoNothing()
      .returning();

    if (!company) continue;
    companiesCreated += 1;

    if (demoCompany.contact) {
      const [contact] = await db
        .insert(recruiterContacts)
        .values({
          companyId: company.id,
          email: demoCompany.contact.email,
          role: demoCompany.contact.role,
          sourceUrl: `${demoCompany.website}/careers`,
          sourceType: demoCompany.contact.verification === "VERIFIED_PUBLIC" ? "CAREERS_PAGE" : "WEBSITE",
          confidence: demoCompany.contact.confidence,
          verification: demoCompany.contact.verification,
          notes:
            demoCompany.contact.verification === "VERIFIED_PUBLIC"
              ? "Demonstration contact — source recorded."
              : "Demonstration contact inferred from an observed public pattern — verify before sending.",
        })
        .onConflictDoNothing()
        .returning();
      if (contact) contactsCreated += 1;
    }

    for (const demoJob of demoCompany.jobs) {
      const dedupeHash = jobFingerprint({ company: demoCompany.name, title: demoJob.title, location: demoJob.location, source: demoJob.source });
      const [job] = await db
        .insert(jobListings)
        .values({
          userId,
          companyId: company.id,
          title: demoJob.title,
          location: demoJob.location,
          remote: demoJob.remote,
          seniority: demoJob.seniority,
          employmentType: "FULL_TIME",
          description: demoJob.description,
          skills: demoJob.skills,
          requirements: demoJob.skills,
          salaryMin: demoJob.salaryMin,
          salaryMax: demoJob.salaryMax,
          currency: "EUR",
          source: demoJob.source,
          sourceUrl: `${demoCompany.website}/careers/${demoJob.title.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`,
          postedAt: new Date(Date.now() - demoJob.postedDaysAgo * 86_400_000),
          dedupeHash,
        })
        .onConflictDoNothing()
        .returning();

      if (job) {
        createdJobs.push(job);
        jobToCompany.set(job.id, company);
        jobsCreated += 1;
      }
    }
  }

  // ── Scores ────────────────────────────────────────────────────
  let applicationsCreated = 0;
  if (profile) {
    const scored = createdJobs
      .map((job) => {
        const base = scoreJob({ profile, job, language: profile.preferredLanguage });
        return {
          job,
          match: { ...base, explanation: heuristicExplanation(base, { profile, job }, profile.preferredLanguage ?? "en") },
        };
      })
      .sort((a, b) => b.match.score - a.match.score);

    const [primaryCv] = await db.select().from(cvDocuments).where(eq(cvDocuments.userId, userId)).orderBy(cvDocuments.createdAt).limit(1);

    for (const { job, match } of scored) {
      await db
        .insert(jobMatches)
        .values({
          jobId: job.id,
          userId,
          score: match.score,
          breakdown: match.breakdown,
          explanation: match.explanation,
          matchedSkills: match.matchedSkills,
          missingSkills: match.missingSkills,
        })
        .onConflictDoNothing();

      // Prepare full drafts for the top-scoring roles, leave the rest discovered.
      if (applicationsCreated >= DEMO_STATUSES.length || match.score < 55) continue;

      const company = jobToCompany.get(job.id);
      if (!company) continue;

      const status = DEMO_STATUSES[applicationsCreated];
      const [application] = await db
        .insert(applications)
        .values({
          userId,
          jobId: job.id,
          companyId: company.id,
          cvDocumentId: primaryCv?.id ?? null,
          status,
          mode: "ASSISTED",
          channel: "EMAIL",
          compatibilityScore: match.score,
          recipientEmail: DEMO_COMPANIES.find((c) => c.name === company.name)?.contact?.email ?? null,
          updatedAt: new Date(),
        })
        .onConflictDoNothing()
        .returning();
      if (!application) continue;
      applicationsCreated += 1;

      const emailDraft = await draftEmail({
        profile,
        job,
        company,
        recipientEmail: application.recipientEmail,
        tone: "PROFESSIONAL",
        language: profile.preferredLanguage ?? "en",
      });

      const [email] = await db
        .insert(generatedEmails)
        .values({
          applicationId: application.id,
          userId,
          subject: emailDraft.subject,
          body: emailDraft.body,
          tone: "PROFESSIONAL",
          language: profile.preferredLanguage ?? "en",
          recipientEmail: application.recipientEmail,
          personalizationScore: emailDraft.personalizationScore,
          qualityScore: emailDraft.qualityScore,
          status: ["SENT", "REPLIED", "INTERVIEW"].includes(status) ? "SENT" : status === "SCHEDULED" ? "APPROVED" : "DRAFT",
          model: emailDraft.model,
          promptVersion: PROMPT_VERSION,
          generationMs: emailDraft.latencyMs,
        })
        .returning();

      const letterDraft = await draftCoverLetter({
        profile,
        job,
        company,
        language: profile.preferredLanguage ?? "en",
        style: "PROFESSIONAL",
      });

      await db.insert(coverLetters).values({
        applicationId: application.id,
        jobId: job.id,
        userId,
        title: letterDraft.title,
        content: letterDraft.content,
        plainText: letterDraft.plainText,
        language: profile.preferredLanguage ?? "en",
        style: "PROFESSIONAL",
        model: letterDraft.model,
        promptVersion: PROMPT_VERSION,
        generationMs: letterDraft.latencyMs,
      });

      await db.update(applications).set({ subject: email.subject, updatedAt: new Date() }).where(eq(applications.id, application.id));

      if (status === "SENT" || status === "REPLIED" || status === "INTERVIEW") {
        const sentAt = new Date(Date.now() - (status === "SENT" ? 3 : 9) * 86_400_000);
        await db
          .update(applications)
          .set({ sentAt, approvedAt: new Date(sentAt.getTime() - 86_400_000), followUpDueAt: addBusinessDays(sentAt, 7), updatedAt: new Date() })
          .where(eq(applications.id, application.id));

        await db.insert(emailMessages).values({
          userId,
          applicationId: application.id,
          direction: "OUTBOUND",
          from: profile.email ?? "me@example.com",
          to: application.recipientEmail ?? "careers@example.com",
          subject: email.subject,
          snippet: email.body.slice(0, 180),
          body: email.body,
          receivedAt: sentAt,
        });

        if (status === "REPLIED" || status === "INTERVIEW") {
          const repliedAt = new Date(sentAt.getTime() + 2 * 86_400_000);
          await db.update(applications).set({ repliedAt, followUpDueAt: null, interviewAt: status === "INTERVIEW" ? new Date(Date.now() + 4 * 86_400_000) : null, updatedAt: new Date() }).where(eq(applications.id, application.id));
          await db.insert(emailMessages).values({
            userId,
            applicationId: application.id,
            direction: "INBOUND",
            from: application.recipientEmail ?? "careers@example.com",
            to: profile.email ?? "me@example.com",
            subject: `Re: ${email.subject}`,
            snippet: "Thanks for your application — we would like to schedule a short conversation next week.",
            body: "Hello,\n\nThanks for your application and the thoughtful cover letter. We reviewed your profile and would like to schedule a 30-minute conversation with the team next week.\n\nAre you available Tuesday afternoon or Thursday morning?\n\nBest regards,\nTalent Acquisition",
            isReply: true,
            receivedAt: repliedAt,
          });
        } else {
          await db.insert(followUps).values({
            applicationId: application.id,
            userId,
            sequence: 1,
            subject: `Follow-up – ${job.title}`,
            body: `Hello,\n\nI wanted to follow up on my application for the ${job.title} role sent on ${sentAt.toLocaleDateString("en-US")}. I remain very interested and happy to share more detail about my recent work.\n\nBest regards,\n${profile.fullName ?? "Candidate"}`,
            language: profile.preferredLanguage ?? "en",
            status: "DRAFT",
            dueAt: addBusinessDays(sentAt, 7),
          });
        }
      }

      if (status === "SCHEDULED") {
        await db.update(applications).set({ scheduledFor: new Date(Date.now() + 86_400_000), approvedAt: new Date(), updatedAt: new Date() }).where(eq(applications.id, application.id));
      }
    }
  }

  await db.insert(activityEvents).values([
    { userId, agent: "DISCOVERY", type: "SUCCESS", message: `Demonstration dataset loaded — ${jobsCreated} listing(s) across ${companiesCreated} companies`, meta: { demo: true } },
    { userId, agent: "RESEARCH", type: "SUCCESS", message: `${companiesCreated} compan(ies) researched with ${contactsCreated} recruitment contact(s)`, meta: { demo: true } },
    { userId, agent: "MATCHING", type: "INFO", message: "Compatibility scores computed for every demonstration listing", meta: { demo: true } },
    { userId, agent: "EMAIL", type: "SUCCESS", message: `Personalized emails drafted for ${applicationsCreated} application(s)`, meta: { demo: true } },
    { userId, agent: "AUTOMATION", type: "WARNING", message: "Demo mode: nothing will be sent until you connect a mailbox and approve", meta: { demo: true } },
  ]);

  await db.insert(notifications).values([
    {
      userId,
      title: "Demonstration data loaded",
      body: "Explore the dashboard, then clear it from Settings → Data when you are ready for live applications.",
      type: "INFO",
      href: "/dashboard",
    },
  ]);

  await updateAgentRun(run.id, userId, {
    status: "COMPLETED",
    progress: 100,
    message: "Demonstration dataset ready",
    promptVersion: PROMPT_VERSION,
    output: { companies: companiesCreated, jobs: jobsCreated, applications: applicationsCreated },
  });

  await recordActivity({
    userId,
    agent: "DISCOVERY",
    message: `Demonstration dataset loaded — ${companiesCreated} companies, ${jobsCreated} jobs, ${applicationsCreated} applications`,
    type: "SUCCESS",
    meta: { demo: true },
  });

  return { companies: companiesCreated, jobs: jobsCreated, applications: applicationsCreated, contacts: contactsCreated, seeded: true };
}

/** Removes demonstration data (keeps the user's own CV, profile and settings). */
export async function clearDemoData(userId: string) {
  const db = getDb();

  const userCompanies = await db.select({ id: companies.id }).from(companies).where(eq(companies.userId, userId));
  const companyIds = userCompanies.map((row) => row.id);

  if (companyIds.length) {
    const userJobs = await db.select({ id: jobListings.id }).from(jobListings).where(eq(jobListings.userId, userId));
    const jobIds = userJobs.map((row) => row.id);

    if (jobIds.length) {
      const userApplications = await db.select({ id: applications.id }).from(applications).where(eq(applications.userId, userId));
      const applicationIds = userApplications.map((row) => row.id);
      if (applicationIds.length) {
        await db.delete(emailMessages).where(inArray(emailMessages.applicationId, applicationIds));
        await db.delete(followUps).where(inArray(followUps.applicationId, applicationIds));
        await db.delete(generatedEmails).where(inArray(generatedEmails.applicationId, applicationIds));
        await db.delete(coverLetters).where(inArray(coverLetters.applicationId, applicationIds));
      }
      await db.delete(applications).where(eq(applications.userId, userId));
      await db.delete(jobMatches).where(eq(jobMatches.userId, userId));
      await db.delete(jobListings).where(eq(jobListings.userId, userId));
    }
    await db.delete(recruiterContacts).where(inArray(recruiterContacts.companyId, companyIds));
    await db.delete(companies).where(eq(companies.userId, userId));
  }

  await db.delete(activityEvents).where(eq(activityEvents.userId, userId));
  await db.delete(notifications).where(eq(notifications.userId, userId));
  await db.update(users).set({ demoMode: false, updatedAt: new Date() }).where(eq(users.id, userId));

  await recordActivity({ userId, agent: "AUTOMATION", message: "Demonstration data cleared", type: "SUCCESS" });

  return { cleared: true };
}
