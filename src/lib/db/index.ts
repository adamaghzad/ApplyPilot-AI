
import fs from "node:fs";
import path from "node:path";

import { PGlite } from "@electric-sql/pglite";
import { drizzle as drizzlePglite } from "drizzle-orm/pglite";
import type { NodePgDatabase } from "drizzle-orm/node-postgres";

import * as schema from "./schema";

export type AppDb = NodePgDatabase<typeof schema>;
export type DbDriver = "pglite" | "postgres";

type DbHandle = {
  db: AppDb;
  driver: DbDriver;
  /** Resolves once schema migrations have been applied. */
  ready: Promise<AppDb>;
};

const globalForDb = globalThis as unknown as { __applyPilotDb?: DbHandle };

function resolveDriver(): { driver: DbDriver; url: string } {
  const raw = process.env.DATABASE_URL?.trim();
  if (!raw) return { driver: "pglite", url: "./.pgdata" };
  if (raw.startsWith("postgres://") || raw.startsWith("postgresql://")) return { driver: "postgres", url: raw };
  if (raw.startsWith("file:")) return { driver: "pglite", url: raw.replace(/^file:\/*/, "") || "./.pgdata" };
  return { driver: "pglite", url: raw };
}

function createDb(): { db: AppDb; driver: DbDriver } {
  const { driver, url } = resolveDriver();

  if (driver === "postgres") {
    // Required lazily so the `pg` driver is only loaded when a real server is configured.
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    const { Pool } = require("pg") as typeof import("pg");
    const { drizzle } = require("drizzle-orm/node-postgres") as typeof import("drizzle-orm/node-postgres");
    const pool = new Pool({ connectionString: url, max: Number(process.env.DATABASE_POOL_MAX ?? 10) });
    return { db: drizzle(pool, { schema }) as AppDb, driver };
  }

  const dataDir = path.isAbsolute(url) ? url : path.join(process.cwd(), url);
  fs.mkdirSync(dataDir, { recursive: true });
  const client = new PGlite(dataDir);
  return { db: drizzlePglite(client, { schema }) as unknown as AppDb, driver };
}

/**
 * Applies SQL migrations from `drizzle/` on first use. Idempotent — drizzle records
 * applied migrations in `drizzle.__drizzle_migrations`.
 */
/**
 * Applies the SQL files generated by `drizzle-kit generate`.
 *
 * Implemented directly instead of via drizzle's migrator helper: the bundled runtime
 * hands a foreign-realm `URL` to `fs`, which Node rejects. Behaviour is identical —
 * migrations are recorded in `drizzle.__drizzle_migrations` and skipped once applied.
 */
async function runMigrations(db: AppDb, driver: DbDriver): Promise<AppDb> {
  const migrationsFolder = path.join(process.cwd(), "drizzle");
  const journalPath = path.join(migrationsFolder, "meta", "_journal.json");
  if (!fs.existsSync(journalPath)) {
    console.warn("[db] No migration journal found — run `npm run db:generate`.");
    return db;
  }

  type Journal = { entries: { idx: number; tag: string }[] };
  const journal = JSON.parse(fs.readFileSync(journalPath, "utf8")) as Journal;

  const run = async (statement: string) => {
    if (driver === "postgres") {
      await (db as unknown as { execute: (q: unknown) => Promise<unknown> }).execute({ sql: statement, params: [] });
    } else {
      const client = (db as unknown as { $client?: { exec?: (sql: string) => Promise<unknown> } }).$client;
      if (client?.exec) await client.exec(statement);
      else await (db as unknown as { execute: (q: unknown) => Promise<unknown> }).execute(statement);
    }
  };

  try {
    await run(`CREATE SCHEMA IF NOT EXISTS "drizzle";`);
    await run(
      `CREATE TABLE IF NOT EXISTS "drizzle"."__drizzle_migrations" ("id" SERIAL PRIMARY KEY, "hash" text NOT NULL, "created_at" bigint);`,
    );

    const { sql } = await import("drizzle-orm");
    const appliedRows = await db.execute<{ hash: string }>(sql`select hash from "drizzle"."__drizzle_migrations"`);
    const applied = new Set(
      ((appliedRows as unknown as { rows?: { hash: string }[] }).rows ?? []).map((row) => row.hash),
    );

    let appliedCount = 0;
    for (const entry of journal.entries) {
      if (applied.has(entry.tag)) continue;
      const file = path.join(migrationsFolder, `${entry.tag}.sql`);
      if (!fs.existsSync(file)) continue;
      const statements = fs.readFileSync(file, "utf8");
      await run(statements);
      await run(`INSERT INTO "drizzle"."__drizzle_migrations" ("hash", "created_at") VALUES ('${entry.tag}', ${Date.now()});`);
      appliedCount += 1;
    }

    console.log(`[db] schema ready (driver=${driver}${appliedCount ? `, applied ${appliedCount} migration(s)` : ""})`);
  } catch (error) {
    console.error("[db] migration failed:", error);
    throw error;
  }
  return db;
}

function handle(): DbHandle {
  if (!globalForDb.__applyPilotDb) {
    const { db, driver } = createDb();
    globalForDb.__applyPilotDb = { db, driver, ready: runMigrations(db, driver) };
  }
  return globalForDb.__applyPilotDb;
}

/**
 * Synchronous accessor for the typed database. Both drivers connect lazily, so
 * queries issued immediately are buffered until the engine is ready.
 */
export function getDb(): AppDb {
  return handle().db;
}

/**
 * Await before touching data in code paths that must not race the initial
 * migration (API routes, seeds, CLI scripts). Cheap: the promise is cached.
 */
export function dbReady(): Promise<AppDb> {
  return handle().ready;
}

export function dbDriver(): DbDriver {
  return handle().driver;
}

export { schema };
export * from "./schema";
